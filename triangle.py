def area(a, h): 
    '''
    Принимает два десятичных числа a и h.
    Возвращает произведение чисел a и h, делённое на 2 (площадь треугольника по формуле S = a * h / 2).
    '''
    return a * h / 2 


def perimeter(a, b, c):
    '''
    Принимает три десятичных числа a, b и c.
    Возвращает сумму числе a, b и с (периметр треугольника по формуле P = a + b + c).
    '''
    return a + b + c 