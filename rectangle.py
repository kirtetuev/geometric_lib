def area(a, b):
    '''
    Принимает два десятичных числа a и b.
    Возвращает произведение чисел a и b (площадь прямоугольника по формуле S = ab).
    ''' 
    return a * b 


def perimeter(a, b):
    '''
    Принимает два десятичных числа a и b.
    Возвращает удвоенную сумму чисел a и b (периметр прямоугольника по формуле S = 2a + 2b).
    ''' 
    return (a + b) * 2