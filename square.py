def area(a):
    '''
    Принимает десятичное число a.
    Возвращает квадрат числа a (площадь квадрата по форумуле S = a²).
    '''
    return a * a


def perimeter(a):
    '''
    Принимает десятичное число a.
    Возвращает число a, умноженное на 4 (периметр квадрата по формуле P = 4a).
    '''
    return 4 * a